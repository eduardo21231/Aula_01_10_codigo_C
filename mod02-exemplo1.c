#include <stdio.h>

int main() {
    // 1. Criar a variável x e atribuir um valor
    int x = 15;

    // 2. Criar a variável y e atribuir um valor
    int y = 25;

    // 3. Criar a variável soma e guardar o resultado
    int soma = x + y;

    // Exibir os valores
    printf("Valor de x: %d\n", x);
    printf("Valor de y: %d\n", y);
    printf("Soma de x + y: %d\n", soma);

    return 0;
}